"""Plugin-routed task imports and non-destructive legacy library migration."""

import json
from pathlib import Path

from .plugins import normalize_task

SCHEMA = "devicehub.task.v2"
LEGACY_SCHEMA = "devicehub.task.v1"
MAX_BYTES = 2 * 1024 * 1024


def decode_json(data):
    if len(data) > MAX_BYTES:
        raise ValueError("任务文件超过 2 MB")
    value = json.loads(data.decode("utf-8-sig"))
    if not isinstance(value, dict) or not value:
        raise ValueError("任务必须是非空 JSON 对象")
    return value


def read_document(path):
    path = Path(path)
    if path.stat().st_size > MAX_BYTES:
        raise ValueError("任务文件超过 2 MB")
    return decode_json(path.read_bytes())


def unwrap(raw):
    if raw.get("schema") in {SCHEMA, LEGACY_SCHEMA}:
        document = raw.get("document")
        if not isinstance(document, dict) or not document:
            raise ValueError("缺少任务原始内容")
        return document
    return raw


def write_manifest(path, manifest):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".part")
    temporary.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    temporary.replace(path)


def detected_plugin(document, packages):
    fallback = None
    for package in packages.values():
        for importer in package.manifest.get("imports", []):
            if importer.get("kind") != "file":
                continue
            selector = importer.get("detect")
            if selector and all(key in document for key in selector.get("all", [])) and (
                    not selector.get("any") or any(key in document for key in selector["any"])):
                return package.id
            if importer.get("fallback"):
                fallback = package.id
    if fallback:
        return fallback
    raise ValueError("没有可以处理此任务的插件，请安装对应插件后重新导入")


def inspect_task(package, raw, *, source="本地文件", author="", fallback_title="导入任务"):
    if raw.get("schema") in {SCHEMA, LEGACY_SCHEMA}:
        if raw.get("plugin_id") and raw["plugin_id"] != package.id:
            raise ValueError("任务所属插件与所选插件不一致")
        source, author = raw.get("source") or source, raw.get("author") or author
        fallback_title = raw.get("title") or fallback_title
    plugin = package.load()
    document = unwrap(raw)
    result = plugin.inspect_document(document, source=source, author=author, fallback_title=fallback_title)
    task = package.task(result["task_id"])
    # Stored compatibility labels and settings are regenerated by the selected plugin.
    result = {key: task.get(key, [] if key in {"parameters", "phases", "issues", "notes"} else "")
            for key in ("title", "subtitle", "description", "source", "author", "kind", "entry",
                        "parameters", "phases", "issues", "notes")} | result | {
        "schema": SCHEMA, "plugin_id": package.id, "plugin_version": package.manifest["version"],
        "document": document, "parameters": task["parameters"], "phases": task["phases"],
    }
    return normalize_task(result)


def import_task(packages, plugin_id, *, source=None, file=None):
    if plugin_id not in packages:
        raise ValueError(f"任务插件未安装或不兼容：{plugin_id}")
    package = packages[plugin_id]
    if source is not None:
        document, author, origin = package.load().fetch_source(source)
        return inspect_task(package, document, source=origin, author=author)
    if file is None:
        raise ValueError("缺少任务文件或导入来源")
    return inspect_task(package, read_document(file), source=Path(file).name, fallback_title=Path(file).stem)


def refresh_library(directory, packages):
    errors = []
    for path in sorted(Path(directory).glob("*.json")):
        try:
            raw = read_document(path)
            plugin_id = raw.get("plugin_id") or detected_plugin(unwrap(raw), packages)
            package = packages.get(plugin_id)
            if package is None:
                raise ValueError(f"任务插件未安装或不兼容：{plugin_id}")
            result = inspect_task(package, raw, fallback_title=path.stem)
        except Exception as error:
            errors.append(f"{path.name}：{error}")
            # Keep original documents and user metadata even if a plugin is unavailable.
            try:
                raw = read_document(path)
                if raw.get("schema") not in {SCHEMA, LEGACY_SCHEMA}:
                    continue
                result = dict(raw)
                result["issues"] = [str(error)]
            except Exception:
                continue
        write_manifest(path, result)
    return {"errors": errors}
